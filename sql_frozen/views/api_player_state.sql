CREATE OR REPLACE VIEW doom.api_player_state AS
 SELECT ps.map_id,
    ps.player_thing_id,
    ps.health,
    ps.alive,
    ps.level_tics,
    ps.previous_x,
    ps.previous_y,
    ps.position_x,
    ps.position_y,
    ps.base_z,
    ps.view_z,
    ps.view_angle,
    ps.momentum_x,
    ps.momentum_y,
    ps.bob_strength,
    ps.previous_view_z,
    ps.previous_view_angle,
    ps.sector_id,
    ps.pain_face_tics,
    ps.armor,
    ps.armor_class,
    ps.backpack,
    ps.ammo_bullets,
    ps.ammo_shells,
    ps.ammo_rockets,
    ps.ammo_cells,
    ps.key_blue,
    ps.key_yellow,
    ps.key_red,
    ps.radsuit_tics,
    ps.invis_tics,
    ps.momentum_z,
    ps.damage_count,
    ps.bonus_count,
    ps.light_amp_tics,
    ps.power_map,
    ps.god_mode,
    ps.noclip,
    ps.invuln_tics,
    ps.berserk,
    ps.message,
    ps.message_tics,
    ps.frags,
    ps.death_tics,
    ps.killer_id,
    ps.sprite_frame
   FROM (player_state ps
     JOIN mp_players mp ON (((mp.map_id = ps.map_id) AND (mp.player_thing_id = ps.player_thing_id))))
  WHERE (mp.role_name = doom_caller());
