"""Make the low-detail frame view template from the full-detail one.

    python tools/make_low_detail.py            # writes sql/frame_views/api_frame_idx_slotS_mM_low.sql
    python tools/make_low_detail.py --check    # exit 1 if the file on disk differs

Doom's low detail draws every other column, each twice. Here: only even
columns are computed (the column ranges that make walls, the player sector's
planes, sprites and the weapon step by two; the message keeps even pixels),
and where the eight-pixel row words are made (view_rows) each even column's
byte is also written into its odd neighbour's (same word: for an even x,
x % 8 is 0, 2, 4 or 6). view_words keeps even-column cells only, so an odd
column from any other source cannot mix into the doubled byte. The output is
the full 64,001-byte frame, which the page draws as it is.

Every rewrite is anchored and counted: a renderer update that moves an
anchor makes this fail instead of producing a wrong view.
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FULL = ROOT / "sql" / "frame_views" / "api_frame_idx_slotS_mM.sql"
LOW = ROOT / "sql" / "frame_views" / "api_frame_idx_slotS_mM_low.sql"

# generate_series calls that make screen columns, by a piece of their text
# (arguments, or what follows the call) -> how many there must be
COLUMN_RANGES = {
    "o.screen_x1": 1,                 # occluders (heights_shown culling)
    "b.x_lo, b.x_hi": 1,              # walls
    ") AS x\n  LEFT JOIN (SELECT n.col_x": 2,   # player sector floor and ceiling
    "t.x_lo, t.x_hi": 1,              # sprites
    "GREATEST(0, k.x0)": 1,           # the weapon
}


def _calls(text):
    """(start, end, args) of every generate_series( ... ) call, balanced."""
    for m in re.finditer(r"generate_series\(", text):
        depth, i = 1, m.end()
        while depth:
            depth += {"(": 1, ")": -1}.get(text[i], 0)
            i += 1
        yield m.start(), i, text[m.end():i - 1]


def _split_args(args):
    depth, out, cur = 0, [], ""
    for ch in args:
        if ch == "," and depth == 0:
            out.append(cur); cur = ""
            continue
        depth += {"(": 1, ")": -1}.get(ch, 0)
        cur += ch
    return out + [cur]


def make(full):
    low, n = full, 0
    # 1. column ranges: even columns only
    found = dict.fromkeys(COLUMN_RANGES, 0)
    out, last = [], 0
    for start, end, args in _calls(full):
        context = full[start:end + 60]
        key = next((k for k in COLUMN_RANGES if k in context), None)
        if key is None:
            continue
        parts = _split_args(args)
        if len(parts) != 2:
            sys.exit(f"column range with {len(parts)} arguments: {args!r}")
        lo, hi = parts[0].strip(), parts[1].strip()
        out.append(full[last:start])
        out.append(f"generate_series(({lo}) + (({lo}) & 1), {hi}, 2)")
        last = end
        found[key] += 1
    out.append(full[last:])
    low = "".join(out)
    bad = {k: (found[k], v) for k, v in COLUMN_RANGES.items() if found[k] != v}
    if bad:
        sys.exit(f"column ranges found / expected: {bad}")

    def sub(old, new, count):
        nonlocal low
        got = low.count(old)
        if got != count:
            sys.exit(f"anchor found {got} times, expected {count}: {old[:70]!r}")
        low = low.replace(old, new)

    # 2. the message: even pixels only
    sub("WHERE mp.x BETWEEN 0 AND rs.screen_w - 1 AND mp.y BETWEEN 0 AND rs.screen_h - 1) m",
        "WHERE mp.x BETWEEN 0 AND rs.screen_w - 1 AND mp.y BETWEEN 0 AND rs.screen_h - 1"
        " AND (mp.x & 1) = 0) m", 1)
    # 3. view_words: even-column cells only (cell = x << 4 | g)
    sub("  FROM view_lanes\n  GROUP BY cell\n),\nview_rows AS (",
        "  FROM view_lanes\n  WHERE ((cell >> 4) & 1) = 0\n  GROUP BY cell\n),\nview_rows AS (", 1)
    # 4. view_rows: each even column's byte also in its odd neighbour's
    for j in range(16):
        sub(f"bit_or(b{j} << sh) AS r{j}," if j < 15 else f"bit_or(b{j} << sh) AS r{j}\n",
            (f"bit_or((b{j} << sh) | (b{j} << (sh - 8))) AS r{j}," if j < 15
             else f"bit_or((b{j} << sh) | (b{j} << (sh - 8))) AS r{j}\n"), 1)
    # 5. the template's own name, and a note on where it comes from
    sub("CREATE OR REPLACE FUNCTION doom.frame_view_template_api_frame_idx()",
        "CREATE OR REPLACE FUNCTION doom.frame_view_template_api_frame_idx_low()", 1)
    head = ("-- GENERATED by tools/make_low_detail.py from api_frame_idx_slotS_mM.sql: do\n"
            "-- not edit; edit the full-detail template and run it again. Low detail: the\n"
            "-- view api_frame_idx_slot<slot>_m<map>_low computes even columns only and\n"
            "-- draws each twice (see the tool's docstring).\n")
    return head + low


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="only compare with the file on disk")
    args = ap.parse_args()
    low = make(FULL.read_text())
    if args.check:
        same = LOW.exists() and LOW.read_text() == low
        print("up to date" if same else f"{LOW.name} differs from what the tool makes")
        sys.exit(0 if same else 1)
    LOW.write_text(low)
    print(f"wrote {LOW.relative_to(ROOT)} ({len(low)} bytes)")


if __name__ == "__main__":
    main()
